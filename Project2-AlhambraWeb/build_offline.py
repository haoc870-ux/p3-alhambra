"""Build the file:// compatible 3D player using only Python's standard library.
Run again after editing motif-detail-3d.js or its reference image/geometry.
"""
from pathlib import Path
import re, base64

root = Path(__file__).resolve().parent
vendor = root / 'assets' / 'vendor'
core = (vendor / 'three.core.js').read_text()
renderer = (vendor / 'three.module.js').read_text()

def bindings(items, importing=False):
    result=[]
    for item in items.split(','):
        pair=re.split(r'\s+as\s+',item.strip())
        if not pair[0]: continue
        local, public = pair[0], pair[-1]
        result.append(f'{local}: {public}' if importing else f'{public}: {local}')
    return ','.join(result)

core_exports=re.search(r'^export\s*\{(.*?)\};\s*$',core,re.M)
assert core_exports
core_object=bindings(core_exports.group(1))
core=re.sub(r'^export\s*\{.*?\};\s*$','',core,flags=re.M)
imports=re.search(r"^import\s*\{(.*?)\}\s*from './three.core.js';",renderer,re.M)
assert imports
import_object=bindings(imports.group(1),True)
renderer=re.sub(r"^import\s*\{.*?\}\s*from './three.core.js';\s*$",'',renderer,flags=re.M)
renderer=re.sub(r"^export\s*\{.*?\}\s*from './three.core.js';\s*$",'',renderer,flags=re.M)
exports=re.search(r'^export\s*\{(.*?)\};\s*$',renderer,re.M)
assert exports
renderer_object=bindings(exports.group(1))
renderer=re.sub(r'^export\s*\{.*?\};\s*$','',renderer,flags=re.M)

player=(root/'motif-detail-3d.js').read_text()
player=re.sub(r"^import \* as THREE from './assets/vendor/three.module.js';",'',player,flags=re.M)
fetch="fetch('assets/motif-photo-geometry.json').then(r=>{if(!r.ok)throw Error('Missing photo geometry');return r.json();})"
assert fetch in player
player=player.replace(fetch,'Promise.resolve('+ (root/'assets/motif-photo-geometry.json').read_text() +')')
image='data:image/png;base64,'+base64.b64encode((root/'assets/motif-user-beaded.png').read_bytes()).decode()
player=player.replace("new THREE.TextureLoader().loadAsync('assets/motif-user-beaded.png')",'new THREE.TextureLoader().loadAsync('+repr(image)+')')
output='''// Offline build: Three.js (MIT) and local photo data, no network requests or ES modules.
// Generated by build_offline.py; original source and licence are included.
(() => {\nconst THREE=(()=>{\nconst core=(()=>{\n'''+core+'\nreturn {'+core_object+'''};})();
return (({'''+import_object+'''})=>{\n'''+renderer+'\nreturn {...core,'+renderer_object+'''};})(core);})();
'''+player+'\n})();\n'
assert not re.search(r'^(?:import|export)\s',output,re.M)
(root/'motif-detail-offline.js').write_text(output)
print('Offline player built:',len(output),'characters')
